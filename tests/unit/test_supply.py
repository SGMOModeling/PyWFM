def _model(tmp_path, diver_specs):
    (tmp_path / "GW").mkdir()
    (tmp_path / "Stream").mkdir()
    files = {"Simulation_MAIN.IN": SIM_MAIN, "GW/GW_MAIN.dat": GW_MAIN,
             "GW/Pump_MAIN.dat": PUMP_MAIN, "GW/ElemPump.dat": ELEM_PUMP, "GW/Wells.dat": WELLS,
             "Stream/Stream_MAIN.dat": STREAM_MAIN, "Stream/DiverSpecs.dat": diver_specs}
    for name, text in files.items():
        (tmp_path / name).write_text(text, encoding="latin-1")
    return tmp_path / "Simulation_MAIN.IN"


def _record(div_ids, n_data=3):
    t = ["10/31/1990_24:00", "11/30/1990_24:00"]
    elem = pd.DataFrame([[-5.0, 0.0, -2.5], [-6.0, 0.0, -1.5]], index=t, columns=[73, 193, 333])
    wells = pd.DataFrame([[-1.0, -1.0], [-2.0, -2.0]], index=t, columns=[11, 12])
    divs = pd.DataFrame([[10.0 * d for d in div_ids]] * 2, index=t, columns=div_ids)
    data = pd.DataFrame(np.arange(2 * n_data, dtype=float).reshape(2, n_data), index=t,
                        columns=list(range(1, n_data + 1)))
    return SupplyRecord(elem, wells, divs, data)


def _numbers(path):
    lines = path.read_text(encoding="latin-1").splitlines()
    return [supply._numbers(lines[i])[0] for i in supply._data_lines(lines)]


def test_freeze_writes_frozen_copies(tmp_path):
    sim = _model(tmp_path, DIVER_SPECS_42)
    out = freeze_supply_adjustment(str(sim), _record([1, 2]))
    text = (tmp_path / "Simulation_MAIN_frozen.IN").read_text(encoding="latin-1")
    assert out.endswith("Simulation_MAIN_frozen.IN")
    assert "GW\\GW_MAIN_frozen.dat" in text and "Stream\\Stream_MAIN_frozen.dat" in text
    assert [ln.split()[0] for ln in text.splitlines() if "/ KOPTDV" in ln] == ["00"]
    assert "GW\\Pump_MAIN_frozen.dat" in (tmp_path / "GW/GW_MAIN_frozen.dat").read_text()
    pump_main = (tmp_path / "GW/Pump_MAIN_frozen.dat").read_text()
    for name in ("Wells_frozen.dat", "ElemPump_frozen.dat", "TSPumping_frozen.dat", "Pumping.out"):
        assert name in pump_main
    # originals untouched
    assert (tmp_path / "Simulation_MAIN.IN").read_text(encoding="latin-1") == SIM_MAIN


def test_element_pumps_get_own_columns(tmp_path):
    sim = _model(tmp_path, DIVER_SPECS_42)
    freeze_supply_adjustment(str(sim), _record([1, 2]))
    records = _numbers(tmp_path / "GW/ElemPump_frozen.dat")[1:4]
    # ID ICOLSK FRACSK IOPTSK FRACSKL(1) FRACSKL(2) TYPDSTSK DSTSK ICFIRIGSK ICADJSK ICSKMAX FSKMAX
    assert [r[:4] for r in records] == [["73", "1", "1.0", "0"], ["193", "2", "1.0", "0"],
                                        ["333", "3", "1.0", "0"]]
    assert all(r[9:] == ["0", "0", "1.0"] for r in records)
    assert records[0][4:9] == ["1.0", "1.0", "4", "1", "2"]   # layers, destination kept
    # pump 193 pumps nothing, so it shares the zero column 2; wells get 4 and 5
    wells = _numbers(tmp_path / "GW/Wells_frozen.dat")[6:8]
    assert [w[:4] for w in wells] == [["11", "4", "1.0", "0"], ["12", "5", "1.0", "0"]]
    data = _numbers(tmp_path / "GW/TSPumping_frozen.dat")
    assert data[0] == ["5"]                       # NCOLPUMP
    lines = (tmp_path / "GW/TSPumping_frozen.dat").read_text().splitlines()
    first = [ln for ln in lines if ln.startswith("10/31/1990_24:00")][0].split()[1:]
    assert [float(v) for v in first] == [-5.0, 0.0, -2.5, -1.0, -1.0]


def test_records_are_matched_by_position(tmp_path):
    """Element pumping IDs may repeat (C2VSimFG: an element's ag and urban
    pumping share its ID), so records are matched by position."""
    sim = _model(tmp_path, DIVER_SPECS_42)
    (tmp_path / "GW/ElemPump.dat").write_text(ELEM_PUMP.replace("  193 ", "  73  "), encoding="latin-1")
    rec = _record([1, 2])
    rec.element_pumping.columns = [73, 73, 333]
    freeze_supply_adjustment(str(sim), rec)
    records = _numbers(tmp_path / "GW/ElemPump_frozen.dat")[1:4]
    assert [r[:2] for r in records] == [["73", "1"], ["73", "2"], ["333", "3"]]


def test_record_count_must_match(tmp_path):
    sim = _model(tmp_path, DIVER_SPECS_42)
    rec = _record([1, 2])
    rec.element_pumping = rec.element_pumping.iloc[:, :2]
    with pytest.raises(ValueError, match="3 records, the recording 2"):
        freeze_supply_adjustment(str(sim), rec)


@pytest.mark.parametrize("specs, n_fields", [(DIVER_SPECS_42, 16), (DIVER_SPECS_40, 14)])
def test_diversions_use_their_own_columns(tmp_path, specs, n_fields):
    sim = _model(tmp_path, specs)
    div_ids = [1, 2] if n_fields == 16 else [1]
    freeze_supply_adjustment(str(sim), _record(div_ids))
    records = _numbers(tmp_path / "Stream/DiverSpecs_frozen.dat")[1:1 + len(div_ids)]
    for k, r in enumerate(records):
        assert len(r) == n_fields
        assert r[2:4] == ["0", "1.0"] and r[-1] == "0"         # no maximum, no adjustment
        cols = [r[i] for i in ((4, 6, 8, 12) if n_fields == 16 else (4, 6, 10))]
        assert set(cols) == {str(3 + k + 1)}                    # after the 3 original columns
        fracs = [float(r[i]) for i in ((5, 7, 9, 13) if n_fields == 16 else (5, 7, 11))]
        assert sum(fracs) == pytest.approx(1.0)
    lines = (tmp_path / "Stream/Diversions_frozen.dat").read_text().splitlines()
    first = [ln for ln in lines if ln.startswith("10/31/1990_24:00")][0].split()[1:]
    assert [float(v) for v in first] == [0.0, 1.0, 2.0] + [10.0 * d for d in div_ids]
    # the 4.2 file keeps the diversion names
    if n_fields == 16:
        assert "Urban One" in (tmp_path / "Stream/DiverSpecs_frozen.dat").read_text()


def test_diversion_components_in_different_columns(tmp_path):
    """Components in different data columns get a column each: the recorded
    diversion times that step's ratio of the component to the total read."""
    specs = DIVER_SPECS_40.replace("1   0.54", "2   0.54")   # non-recoverable loss from column 2
    sim = _model(tmp_path, specs)
    freeze_supply_adjustment(str(sim), _record([1]))
    r = _numbers(tmp_path / "Stream/DiverSpecs_frozen.dat")[1]
    assert [r[i] for i in (4, 6, 10)] == ["4", "5", "6"]       # after the 3 original columns
    assert [r[i] for i in (5, 7, 11)] == ["1.0", "1.0", "1.0"]
    lines = (tmp_path / "Stream/Diversions_frozen.dat").read_text().splitlines()
    rows = [[float(v) for v in ln.split()[1:]] for ln in lines if ln[:2] in ("10", "11")]
    # data columns are [0, 1, 2] then [3, 4, 5]; recorded diversion 10
    read = np.array([[0 * 0.03, 1 * 0.54, 0 * 0.43], [3 * 0.03, 4 * 0.54, 3 * 0.43]])
    expected = 10.0 * read / read.sum(axis=1, keepdims=True)
    np.testing.assert_allclose([row[3:] for row in rows], expected)
    np.testing.assert_allclose([sum(row[3:]) for row in rows], [10.0, 10.0])


def test_component_ratios_persist_through_zero_totals():
    read = np.array([[0.0, 0.0], [1.0, 3.0], [0.0, 0.0]])
    np.testing.assert_allclose(supply._component_ratios(read),
                               [[0.0, 1.0], [0.25, 0.75], [0.25, 0.75]])


def test_long_rows_wrap(tmp_path):
    path = tmp_path / "ts.dat"
    supply.write_time_series_file(str(path), np.arange(25.0).reshape(1, 25), ["10/31/1990_24:00"],
                                  "t", "NCOLPUMP")
    lines = [ln for ln in path.read_text().splitlines() if not supply._is_comment(ln)][5:]
    assert len(lines) == 3 and lines[1].startswith(" ")
    values = [float(v) for ln in lines for v in ln.split()[(1 if ln[0] != " " else 0):]]
    assert values == list(range(25))
